#!/usr/bin/env node
/**
 * Regenerates packages/runtime/src/provider/model-snapshot.ts from kiso.work's
 * list of every text model (owner, 2026-11-11: each release takes a fresh copy).
 * A release step, never part of `npm run check` (it reads the network). Strict:
 * a failed or empty download stops the release instead of shipping old data.
 *
 *   node scripts/model-snapshot.mjs                  # fetch, write the snapshot
 *   node scripts/model-snapshot.mjs --from all.json  # from a local copy
 *   node scripts/model-snapshot.mjs --check          # print what a fresh copy would change
 *
 * What the snapshot is used for (packages/runtime/src/provider/metadata.ts):
 *  - whether a model reads pictures, where no row of the table says so;
 *  - a context window, as the last step after every row of the same model.
 * Nothing else: no price, no effort levels, no max output (those are a route's
 * own facts and stay with the table's rows).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { isMain } from "./is-main.mjs";

export const SOURCE = "https://kiso.work/models/all.json";
const OUTPUT = new URL("../packages/runtime/src/provider/model-snapshot.ts", import.meta.url);

/** The key a model is found by: vendor prefix off, lower case. */
export const fold = (id) => id.slice(id.lastIndexOf("/") + 1).toLowerCase();

export function rowsOf(feed) {
	if (!Array.isArray(feed?.models) || feed.models.length < 100) throw new Error(`${SOURCE}: expected the full list, got ${feed?.models?.length ?? "no"} models`);
	const rows = {};
	for (const m of feed.models) {
		if (typeof m.id !== "string") continue;
		const key = fold(m.id);
		if (rows[key] !== undefined) continue; // the first (most used) listing of a name stands
		const input = Array.isArray(m.inputModalities) ? m.inputModalities.filter((x) => typeof x === "string") : null;
		const window = Number.isInteger(m.contextWindow) && m.contextWindow > 0 ? m.contextWindow : null;
		if (input === null && window === null) continue;
		rows[key] = { input, window };
	}
	return rows;
}

export function render(rows, asOf) {
	const lines = Object.keys(rows).sort().map((k) => `\t${JSON.stringify(k)}: ${JSON.stringify(rows[k])},`);
	return `/**
 * GENERATED by scripts/model-snapshot.mjs from ${SOURCE} (as of ${asOf}).
 * Do not edit by hand: a release runs the script and commits the diff.
 */

export const MODEL_SNAPSHOT_AS_OF = ${JSON.stringify(asOf)};
export const MODEL_SNAPSHOT_SOURCE = ${JSON.stringify(SOURCE)};

/** Keyed by the model's name with its vendor prefix off, in lower case. */
export const MODEL_SNAPSHOT: Readonly<Record<string, { readonly input: readonly string[] | null; readonly window: number | null }>> = {
${lines.join("\n")}
};
`;
}

if (isMain(import.meta.url)) {
	const args = process.argv.slice(2);
	const from = args.includes("--from") ? args[args.indexOf("--from") + 1] : null;
	let feed;
	if (from !== null) feed = JSON.parse(readFileSync(from, "utf8"));
	else {
		const res = await fetch(SOURCE, { headers: { Accept: "application/json", "User-Agent": "kiso-release" } });
		if (!res.ok) throw new Error(`${SOURCE} answered ${res.status}`);
		feed = await res.json();
	}
	const asOf = String(feed.generatedAt ?? "").slice(0, 10) || "unknown";
	const text = render(rowsOf(feed), asOf);
	if (args.includes("--check")) {
		const now = readFileSync(OUTPUT, "utf8");
		console.log(now === text ? "model snapshot: current" : "model snapshot: a fresh copy differs (run without --check and commit it)");
		process.exit(now === text ? 0 : 1);
	}
	writeFileSync(OUTPUT, text);
	console.log(`model snapshot: ${Object.keys(rowsOf(feed)).length} models, as of ${asOf}`);
}

#!/usr/bin/env node
/**
 * Regenerates packages/runtime/src/provider/openrouter-rows.ts from
 * OpenRouter's public model list. NOT part of `npm run check` (it reads the
 * network); run it by hand, read the diff, and commit the file with the date.
 *
 *   node scripts/registry-or-rows.mjs                 # fetch, write the rows file
 *   node scripts/registry-or-rows.mjs --from file.json --date 2026-10-17
 *   node scripts/registry-or-rows.mjs --check         # print differences with the committed rows
 *
 * What a row says, and does not:
 *  - OpenRouter's list is the ROUTE's own statement, so these rows are keyed
 *    to that origin and are never copied to another route.
 *  - `effort.levels` come from `reasoning.supported_efforts` and only when
 *    `reasoning_effort` is among the model's supported parameters.
 *  - `effort.default` is ALWAYS null: the router's default can differ from
 *    the vendor's (OpenRouter says high for Opus 5.5; the vendor's page says
 *    medium), and unknown stays null.
 *  - `maxOutputTokens` is dropped where it equals 0.9 x the window (a
 *    router-derived placeholder, not a vendor statement).
 *  - prices are the base rates; a model with a long-prompt tier carries its
 *    base rates (the row says so in a comment).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { isMain } from "./is-main.mjs";

/** the models the owner named on 2026-10-17 */
export const IDS = [
	"anthropic/claude-opus-5.5",
	"anthropic/claude-sonnet-5.5",
	"anthropic/claude-haiku-5.5",
	"openai/gpt-6.1-sol",
	"openai/gpt-6-sol",
	"openai/gpt-6-luna",
	"deepseek/deepseek-v4.1-flash",
	"x-ai/grok-4.7",
	"z-ai/glm-5.3-flash",
	"moonshotai/kimi-k3",
	"xiaomi/mimo-v2.6-flash",
	"google/gemini-4-argon",
];
/** facts a hand-written row held before the generator, kept where evidence in
 *  this repository backs them (GLM-F1: the compat adapter reads GLM's think
 *  from the stream's `reasoning` field; the 2026-09-09 row said automatic caching) */
const KEPT = {
	"z-ai/glm-5.3-flash": { emitsThinkingStream: true, promptCaching: "automatic" },
};
const ORDER = ["none", "minimal", "low", "medium", "high", "xhigh", "max"];
const OUT = new URL("../packages/runtime/src/provider/openrouter-rows.ts", import.meta.url);
const SOURCE = "https://openrouter.ai/api/v1/models";

const perM = (v) => (v === undefined ? null : Math.round(Number(v) * 1e6 * 1e6) / 1e6);

export function rowFor(model, date) {
	const ctx = model.context_length;
	const reported = model.top_provider?.max_completion_tokens ?? null;
	const placeholder = reported !== null && (reported === Math.floor(0.9 * ctx) || reported === Math.floor(0.9 * ctx) - 1);
	const reasoning = model.reasoning ?? null;
	const efforts = reasoning?.supported_efforts;
	const usable = Array.isArray(efforts) && efforts.length > 0 && (model.supported_parameters ?? []).includes("reasoning_effort");
	const levels = usable ? ORDER.filter((l) => efforts.includes(l)) : null;
	const unknown = usable ? efforts.filter((e) => !ORDER.includes(e)) : [];
	if (unknown.length > 0) throw new Error(`${model.id}: efforts outside the registry vocabulary: ${unknown.join(", ")}`);
	const p = model.pricing ?? {};
	const hasTier = Array.isArray(p.overrides) && p.overrides.length > 0;
	return {
		id: model.id,
		hasTier,
		entry: {
			model: model.id,
			endpoint: "https://openrouter.ai",
			capabilities: {
				contextWindow: ctx ?? null,
				maxOutputTokens: reported === null || placeholder ? null : reported,
				promptCaching: KEPT[model.id]?.promptCaching ?? null,
				reasoning: levels === null ? null : { emitsThinkingStream: KEPT[model.id]?.emitsThinkingStream ?? null, thinking: null, effort: { levels, default: null, wire: "reasoning_effort" }, asOf: date, source: SOURCE },
				inputModalities: model.architecture?.input_modalities ?? null,
			},
			capabilitiesAsOf: date,
			capabilitiesSource: SOURCE,
			pricing: p.prompt === undefined ? null : { inputPerM: perM(p.prompt), outputPerM: perM(p.completion), cacheReadPerM: perM(p.input_cache_read) ?? 0, cacheWritePerM: perM(p.input_cache_write) ?? 0, asOf: date, source: SOURCE },
		},
	};
}

function render(rows, date) {
	const body = rows
		.map(({ entry, hasTier }) => `\t${hasTier ? "// a long-prompt tier exists on this route (OpenRouter's pricing.overrides): the row carries the base rates\n\t" : ""}${JSON.stringify(entry)},`)
		.join("\n");
	return `/**
 * GENERATED by scripts/registry-or-rows.mjs from ${SOURCE} on ${date}.
 * Do not edit by hand: run the script and commit the diff. The rules for what
 * a row says (and does not) are in the script's header.
 */
import type { ModelMetadataEntry } from "./metadata.js";

export const OPENROUTER_ROWS: readonly ModelMetadataEntry[] = [
${body}
];
`;
}

if (isMain(import.meta.url)) {
	const args = process.argv.slice(2);
	const arg = (name) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
	const date = arg("--date") ?? new Date().toISOString().slice(0, 10);
	const from = arg("--from");
	const data = from !== undefined ? JSON.parse(readFileSync(from, "utf8")) : await (await fetch(SOURCE)).json();
	const byId = new Map(data.data.map((m) => [m.id, m]));
	const missing = IDS.filter((id) => !byId.has(id));
	if (missing.length > 0) { console.error(`not in OpenRouter's list: ${missing.join(", ")}`); process.exit(1); }
	const rows = IDS.map((id) => rowFor(byId.get(id), date));
	const text = render(rows, date);
	if (args.includes("--check")) {
		const current = readFileSync(OUT, "utf8");
		console.log(current === text ? "openrouter-rows.ts matches the list" : "openrouter-rows.ts DIFFERS from the list (run without --check to regenerate)");
		process.exit(current === text ? 0 : 1);
	}
	writeFileSync(OUT, text);
	console.log(`wrote ${rows.length} rows to packages/runtime/src/provider/openrouter-rows.ts (${date})`);
}
